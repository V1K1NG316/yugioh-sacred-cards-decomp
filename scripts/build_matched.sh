#!/usr/bin/env bash
# Y5: put the matched C functions into the ROM build.
# Run inside WSL from the repo root (the Makefile does it): bash scripts/build_matched.sh
#
# For every src/funcs/<name>.c it compiles the C with agbcc (scripts/match_func.sh) and rewrites
# private/asm/funcs/<name>.s -- the generated disassembly of that one function -- with the
# compiled code, followed by the ROM's own bytes (`.incbin`) up to the extent the ROM gives the function
# (config/functions.csv `size` = distance to the next start, approximation A5). gcc's own leading
# `.align` is dropped: inside rom.s the byte stream is already positioned, and an extra align
# would insert padding the ROM does not have.
# Each function is then checked on its own: the rewritten file, assembled alone, must reproduce
# the ROM's bytes over its whole extent -- before `make compare` ever runs.
# Data files, rom.s and every other generated file are left alone.
set -euo pipefail
REPO=/mnt/d/Yugioh_DeComp_V2
cd "$REPO"

MATCHED=0
BYTES=0
for c in src/funcs/*.c; do
  [ -e "$c" ] || { echo "build_matched: no src/funcs/*.c -- nothing to do"; break; }
  name=$(basename "$c" .c)
  row=$(awk -F, -v n="$name" 'NR > 1 && $2 == n {print $1, $3, $4}' config/functions.csv)
  [ -n "$row" ] || { echo "build_matched: $name is not in config/functions.csv" >&2; exit 1; }
  read -r addr mode size <<< "$row"
  [ "$mode" = thumb ] || { echo "build_matched: $name is $mode, not thumb" >&2; exit 1; }

  bash scripts/match_func.sh "$name" "$addr" "$REPO/src/funcs"
  W="$REPO/private/build/match/$name"
  L1=$(cat "$W/size.txt")
  EXTENT=$(( size ))
  if [ "$L1" -gt "$EXTENT" ]; then
    echo "build_matched: $name is $L1 bytes but the ROM gives it only $EXTENT" >&2; exit 1
  fi
  SLACK=$(( EXTENT - L1 ))

  # Symbols the compiled code references. A function is already a label in the disassembly; a data
  # symbol is not, so it is defined here as an absolute address (`.set`, no low bit) -- what the
  # pool word needs. Anything not named NAME_<8 hex digits> is refused.
  # The list comes from scripts/asm_with_defsyms.sh ($W/$name.o.symrefs), which is also what
  # assembles the object: it already turns each of these into an absolute address for the check's
  # own link, so the finished object does not list them as undefined any more -- `nm -u` alone
  # would come back empty and this file would be left with a symbol nobody defines.
  if [ -f "$W/$name.o.symrefs" ]; then
    refs() { cat "$W/$name.o.symrefs"; }
  else
    refs() { arm-none-eabi-nm -u "$W/$name.o" | awk '{print $NF}'; }
  fi
  SETS=()
  while read -r s; do
    [ -n "$s" ] || continue
    if ! [[ $s =~ ^[A-Za-z_][A-Za-z0-9_]*_([0-9A-Fa-f]{8})$ ]]; then
      echo "build_matched: $name references '$s', which is not a NAME_<8 hex digits> ROM address" >&2
      exit 1
    fi
    if ! awk -F, -v n="$s" 'NR > 1 && $2 == n {found = 1} END {exit !found}' config/functions.csv; then
      SETS+=("	.set	$s, 0x${BASH_REMATCH[1]}")
    fi
  done < <(refs)

  {
    echo "@ $name -- matched C. Generated by scripts/build_matched.sh from src/funcs/$name.c."
    echo "@ Do not edit: the C file is the source, this file is rebuilt on every make."
    # rom.s is `.syntax unified`; agbcc writes divided syntax, where `mov r0, #0` means the
    # 2-byte `movs`, not the 4-byte `mov.w` unified prefers. Bracket the fragment so the
    # assembler reads it exactly as pokefirered reads agbcc output.
    echo "	.syntax divided"
    for l in ${SETS[@]+"${SETS[@]}"}; do echo "$l"; done
    awk '/^[ 	]*\.globl[ 	]/{seen=1} !seen && /^[ 	]*\.align/{next} {print}' "$W/$name.s" \
      | sed -E -e "s/^\.gcc2_compiled\.:/.gcc2_compiled_$name:/" \
               -e "s/\.L([0-9A-Za-z_]+)/.L${name}_\1/g"
    if [ "$SLACK" -gt 0 ]; then
      printf '	.incbin "private/baserom.gba", %d, %s	@ %s ROM bytes past the compiled function (A5 extent; may hold unlisted code)\n' "$(( addr - 0x08000000 + L1 ))" "$SLACK" "$SLACK"
    fi
    echo "	.syntax unified"
  } > "private/asm/funcs/$name.s"

  # Self-check, independent of make compare: this file alone, assembled in the same context as
  # rom.s and linked at the function's address, must reproduce the ROM's bytes over the whole
  # extent (code, literal pool and the zero tail).
  {
    echo '	.include "asm/macros.inc"'
    echo '	.syntax unified'
    echo '	.text'
    echo "	.include \"private/asm/funcs/$name.s\""
  } > "$W/shim.s"
  arm-none-eabi-as -I . -o "$W/shim.o" "$W/shim.s"
  bash scripts/link_at.sh "$W" shim "$W/shim.o" "$addr"
  dd if="$REPO/private/baserom.gba" of="$W/shim_rom.bin" bs=1 count="$EXTENT" \
     skip=$(( addr - 0x08000000 )) status=none
  if ! head -c "$EXTENT" "$W/shim.bin" | cmp -s - "$W/shim_rom.bin"; then
    echo "build_matched: $name does NOT reproduce its $EXTENT ROM bytes:" >&2
    head -c "$EXTENT" "$W/shim.bin" | od -An -tx1 >&2
    od -An -tx1 "$W/shim_rom.bin" >&2
    exit 1
  fi

  printf 'build_matched: %-16s %s at %s: %s bytes of C + %s of ROM tail = %s\n' \
      "$name" "$c" "$addr" "$L1" "$SLACK" "$EXTENT"
  MATCHED=$(( MATCHED + 1 ))
  BYTES=$(( BYTES + L1 ))
done
echo "build_matched: $MATCHED C function(s), $BYTES bytes from C linked into the ROM"
