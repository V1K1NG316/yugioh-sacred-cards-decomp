#!/usr/bin/env python3
"""Turn raw gbadisasm output into private/asm/rom.s that GNU as accepts.

usage: post_disasm.py <raw.s> <rom.s>

Adds the file header (macro include, unified syntax, .text) and appends the few
bytes gbadisasm drops after its final label, so the assembled file is exactly
the ROM.

How the tail is known: a LABEL_DATA prints no line of its own, so the sentinel
`data_label` that tools/make_disasm_cfg.py writes into private/asm/rom.cfg turns
into a plain gap of .byte lines running from the end of the code to the
sentinel; only the last 4 bytes of the ROM (the sentinel's own content) are
dropped. This script checks that shape (no label at or past the sentinel, raw
output ends in a .byte line) and appends those 4 bytes from the ROM. If a future
function list breaks the shape, `make compare` fails on the byte diff.
"""
import re
import sys
from pathlib import Path

BASE = 0x08000000
ROM = Path(__file__).resolve().parents[1] / 'private' / 'baserom.gba'
SENTINEL = BASE + 0x01000000 - 4
LABEL_RE = re.compile(r'^_([0-9A-F]{8}):')
COLUMNS = 16

# A symbol declared with `non_word_aligned_thumb_func_start` carries the Thumb
# function bit (LSB=1) at an address that is only 2-aligned, so GNU as refuses
# the 2-byte encoding of a plain `b <sym>` and silently widens it to a 4-byte
# `b.w`/BL -- bytes the original ROM does not have. `b.n <sym>` forces the
# narrow encoding (verified: same bug reproduced in a 20-line test file, and
# `b.n` fixed it). Only the mnemonics that have a 2-byte form are touched; `bl`
# is always 4 bytes and is left alone.
NARROW_BRANCHES = {'b', 'beq', 'bne', 'bcs', 'bhs', 'bcc', 'blo', 'bmi', 'bpl',
                   'bvs', 'bvc', 'bhi', 'bls', 'bge', 'blt', 'bgt', 'ble', 'bal'}
NWA_START_RE = re.compile(r'^\tnon_word_aligned_thumb_func_start (\S+)$')
BRANCH_TO_RE = re.compile(r'^\t(b[a-z]*)\s+(\S+)$')


def narrow_branches(lines):
    """Force 2-byte branches to non-word-aligned Thumb functions. Returns (lines, n)."""
    targets = {m.group(1) for m in (NWA_START_RE.match(l) for l in lines) if m}
    if not targets:
        return lines, 0
    out = []
    n = 0
    for line in lines:
        m = BRANCH_TO_RE.match(line)
        if m and m.group(1) in NARROW_BRANCHES and m.group(2) in targets:
            out.append('\t%s.n %s' % (m.group(1), m.group(2)))
            n += 1
        else:
            out.append(line)
    return out, n



def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    raw_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    raw = raw_path.read_text(encoding='utf-8', errors='replace')
    lines = raw.splitlines()

    labels = [int(m.group(1), 16) for m in (LABEL_RE.match(l) for l in lines) if m]
    if not labels:
        sys.exit('no labels found in %s' % raw_path)
    if max(labels) >= SENTINEL:
        sys.exit('raw output has a label at or past the sentinel 0x%08X (0x%08X): '
                 'the tail is no longer a fixed 4 bytes' % (SENTINEL, max(labels)))
    if not lines[-1].startswith('\t.byte'):
        sys.exit('raw output does not end in a .byte line: %r' % lines[-1])

    rom = ROM.read_bytes()
    tail = rom[SENTINEL - BASE:]
    lines, narrowed = narrow_branches(lines)
    raw = '\n'.join(lines) + '\n'

    header = [
        '@ Generated by scripts/disasm.sh -- do not edit.',
        '@ Whole-ROM disassembly of private/baserom.gba, function list from config/functions.csv.',
        '',
        '\t.include "asm/macros.inc"',
        '\t.syntax unified',
        '\t.text',
        '',
    ]
    body = [raw]
    body.append('\n@ bytes 0x%08X-0x%08X: after the disassembler\'s final label\n_%08X:\n'
                % (SENTINEL, BASE + len(rom) - 1, SENTINEL))
    for i in range(0, len(tail), COLUMNS):
        chunk = tail[i:i + COLUMNS]
        body.append('\t.byte %s\n' % ', '.join('0x%02X' % b for b in chunk))

    out_path.write_text('\n'.join(header) + ''.join(body), encoding='utf-8', newline='\n')
    print('raw -> %s : %d lines, %d labels, last label 0x%08X' % (raw_path.name, len(lines),
                                                                 len(labels), max(labels)))
    print('wrote %s: %d trailing bytes appended, %d branches narrowed to .n'
          % (out_path, len(tail), narrowed))


if __name__ == '__main__':
    main()
