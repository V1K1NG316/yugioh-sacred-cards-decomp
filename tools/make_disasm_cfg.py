#!/usr/bin/env python3
"""Write private/asm/rom.cfg, the gbadisasm config, from config/functions.csv.

gbadisasm (private/tools/gbadisasm, see docs/credits.md) reads one statement per
line; we emit the two we need:

    arm_func   <address> <name> f      -- an ARM function, "f" = sure it is one
    thumb_func <address> <name> f      -- a THUMB function
    data_label <address>               -- force raw bytes from here on

Every row of config/functions.csv becomes one *_func line (mode column decides
which one) with the "f" flag: the census already decided these are functions, so
gbadisasm must not demote one to a plain label.

The last line is a sentinel `data_label` 4 bytes before the end of the ROM. The
disassembler drops the bytes after its final label, so the sentinel pins the
final label to a known address and private/asm/post_disasm.py appends those last
4 bytes itself.

Read-only apart from private/asm/rom.cfg; prints a summary.
"""
import csv
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]        # works under Windows python and WSL python3
CSV = REPO / 'config' / 'functions.csv'
OUT = REPO / 'private' / 'asm' / 'rom.cfg'
ROM_SIZE = 0x01000000
BASE = 0x08000000
SENTINEL = BASE + ROM_SIZE - 4


def main():
    with CSV.open(newline='') as f:
        rows = list(csv.DictReader(f))
    if not rows:
        sys.exit('functions.csv is empty')

    seen = {}
    lines = [
        '# Generated by tools/make_disasm_cfg.py from config/functions.csv -- do not edit.',
        '# Statements: arm_func / thumb_func <addr> <name> f ; data_label <addr>.',
    ]
    counts = {'arm': 0, 'thumb': 0}
    for row in rows:
        addr = int(row['address'], 16)
        if addr in seen:
            sys.exit('duplicate address 0x%08X (%s and %s)' % (addr, seen[addr], row['name']))
        seen[addr] = row['name']
        mode = row['mode']
        if mode not in counts:
            sys.exit('bad mode %r at 0x%08X' % (mode, addr))
        counts[mode] += 1
        lines.append('%s_func 0x%08X %s f' % (mode, addr, row['name']))

    lines.append('# sentinel: everything from here to the end of the ROM is data')
    lines.append('data_label 0x%08X' % SENTINEL)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', newline='\n')
    print('functions.csv: %d rows (thumb %d, arm %d)' % (len(rows), counts['thumb'], counts['arm']))
    print('wrote %s (%d lines)' % (OUT, len(lines)))


if __name__ == '__main__':
    main()
