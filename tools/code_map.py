#!/usr/bin/env python3
"""Report the code/data split of private/baserom.gba.

Prints, for docs/rom-map.md:
  * how many bytes the disassembly emits as instructions (plus literal pools and
    .align padding) and how many as data (`.incbin` runs), from
    private/asm/rom_full.s -- the Y3 disassembly generated by scripts/disasm.sh;
  * the code block: everything before the first data run of 4 KiB or more;
  * data runs of 4 KiB or more inside that block, each with a one-line reading of
    the bytes at its start (valid THUMB? printable text? zero run?);
  * a 1 MiB block profile of the ROM after the code block (zero / ASCII /
    ROM-pointer density) as a first cut at the data regions.

Without private/asm/rom_full.s (a fresh clone before the first disassembly run) it
falls back to the Y2 view: the extents of config/functions.csv.

Read-only; writes nothing.
"""
import re
import struct
import sys
from array import array
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CSV = REPO / 'config' / 'functions.csv'
ROM = REPO / 'private' / 'baserom.gba'
FULL_S = REPO / 'private' / 'asm' / 'rom_full.s'
BASE = 0x08000000
GAP_MIN = 0x1000        # 4 KiB
TAIL_MIN = 0x100000     # 1 MiB: a data run this big is the bulk data tail, not a pool
BLOCK = 0x100000        # 1 MiB
INCBIN_RE = re.compile(r'^\t\.incbin "([^"]+)", 0x([0-9A-F]+), (\d+)$')

sys.path.insert(0, str(REPO / 'tools'))
import find_functions as F    # thumb_ok / u16 / u32 (same ROM, same base)


def classify(rom, a, n=64):
    chunk = rom[a - BASE:a - BASE + n]
    if all(b == 0 for b in chunk):
        return 'zero run'
    printable = sum(1 for b in chunk if 0x20 <= b < 0x7F)
    if printable >= n * 0.8:
        return 'ASCII text'
    if a % 2 == 0 and F.thumb_ok(a, 4):
        return 'valid THUMB (code-like)'
    return 'not code-like (table/data)'


def read_rows():
    rows = []
    for line in CSV.read_text().splitlines()[1:]:
        a, name, mode, size, source = line.split(',')
        rows.append((int(a, 16), name, mode, int(size), source))
    rows.sort()
    return rows


def data_runs():
    """[(address, length)] of the .incbin lines, or None when there is no rom_full.s."""
    if not FULL_S.exists():
        return None
    runs = []
    for line in FULL_S.read_text(encoding='utf-8').splitlines():
        m = INCBIN_RE.match(line)
        if m:
            runs.append((BASE + int(m.group(2), 16), int(m.group(3))))
    return runs


def profile(rom, start):
    print(f'\nblocks after 0x{start:08X}, 1 MiB each:')
    a = start
    while a < BASE + len(rom):
        chunk = rom[a - BASE:a - BASE + BLOCK]
        n = len(chunk)
        zeros = sum(1 for b in chunk if b == 0)
        printable = sum(1 for b in chunk if 0x20 <= b < 0x7F)
        words = array('I')
        words.frombytes(chunk[:n // 4 * 4])
        ptr = sum(1 for w in words if (w & 0xFE000000) == 0x08000000
                  and (w & 1) and w < BASE + len(rom))
        print(f'  0x{a:08X}  zero {100.0 * zeros / n:5.1f}%  '
              f'ASCII {100.0 * printable / n:5.1f}%  odd-RAM-ptr words {ptr:6d}')
        a += BLOCK


def main():
    rom = ROM.read_bytes()
    rows = read_rows()
    thumb = sum(1 for r in rows if r[2] == 'thumb')
    runs = data_runs()

    print(f'ROM: {len(rom)} bytes (0x{BASE:08X}..0x{BASE + len(rom):08X})')
    print(f'functions: {len(rows)}  (thumb {thumb}, arm {len(rows) - thumb})')

    if runs is None:
        code_bytes = sum(r[3] for r in rows)
        code_end = max(r[0] + r[3] for r in rows)
        print(f'no {FULL_S.name}: Y2 view from the CSV extents')
        print(f'  code bytes: {code_bytes} ({100.0 * code_bytes / len(rom):.2f}% of the ROM)')
        print(f'  code region: 0x{min(r[0] for r in rows):08X}..0x{code_end:08X}')
        profile(rom, (code_end + BLOCK - 1) // BLOCK * BLOCK)
        return

    data_bytes = sum(n for _, n in runs)
    print(f'data runs (.incbin): {len(runs)}  {data_bytes} bytes '
          f'({100.0 * data_bytes / len(rom):.2f}% of the ROM)')
    print(f'instructions + literal pools + padding: {len(rom) - data_bytes} bytes '
          f'({100.0 * (len(rom) - data_bytes) / len(rom):.2f}% of the ROM)')

    big = [r for r in runs if r[1] >= GAP_MIN]
    code_end = min((a for a, n in runs if n >= TAIL_MIN), default=BASE + len(rom))
    print(f'code block: 0x{BASE:08X}..0x{code_end:08X} ({code_end - BASE} bytes) '
          f'= everything before the first data run of {TAIL_MIN} bytes or more '
          f'(the bulk data tail)')

    inside = sorted((r for r in big if r[0] < code_end))
    print(f'\ndata runs >= {GAP_MIN} bytes inside the code block: {len(inside)}')
    for a, n in inside:
        print(f'  0x{a:08X}-0x{a + n:08X}  {n:6d} B  {classify(rom, a)}')

    profile(rom, (code_end + BLOCK - 1) // BLOCK * BLOCK)


if __name__ == '__main__':
    main()
